def _conceder_privilegios() -> None:
    papel = _papel()
    # Rows, never structure. No CREATE, no TRUNCATE, no DDL anywhere.
    for tabela, privs in (
        # No DELETE: AC-0001-14 replaces deletion with anonymisation, so the
        # privilege has no legitimate use and its absence is what makes I4 hold.
        ("usuario", "SELECT, INSERT, UPDATE"),
        ("token_credencial", "SELECT, INSERT, UPDATE"),
        # Operational scratch, purged in place.
        ("tentativa_login", "SELECT, INSERT, UPDATE, DELETE"),
        ("limite_taxa", "SELECT, INSERT, UPDATE, DELETE"),
        # Sessions are evidence of a login; they are revoked, not removed.
        ("sessao_familia", "SELECT, INSERT, UPDATE"),
        ("sessao", "SELECT, INSERT, UPDATE"),
    ):
        op.execute(f"GRANT {privs} ON {tabela} TO {papel}")

    # The audit trail: append and read, and that is all. Stated as a REVOKE as
    # well as a narrow GRANT because privileges are per-partition and a later
    # `GRANT ... ON ALL TABLES IN SCHEMA public` is the line every convenience
    # script contains.
    op.execute(f"GRANT SELECT, INSERT ON historico_movimentacao TO {papel}")
    op.execute(f"REVOKE UPDATE, DELETE, TRUNCATE ON historico_movimentacao FROM {papel}")
